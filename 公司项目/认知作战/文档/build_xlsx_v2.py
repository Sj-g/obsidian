def style_cell(cell, font, fill=None, align=LEFT_WRAP):
    cell.font = font
    if fill is not None:
        cell.fill = fill
    cell.alignment = align


def build_detail_sheet(wb, subsys, sheet_name):
    ws = wb.create_sheet(title=sheet_name)
    # 列宽
    for i, w in enumerate(DETAIL_WIDTHS, start=1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    # 表头
    ws.append(DETAIL_HEADERS)
    for col in range(1, 9):
        c = ws.cell(row=1, column=col)
        style_cell(c, HEADER_FONT, HEADER_FILL, CENTER_WRAP)
    ws.row_dimensions[1].height = 26
    # 子系统行
    ws.append([LEVEL_SUBSYS, subsys["m_id"], subsys["full"], subsys["req"],
               subsys["resp"], "—", subsys["src"], subsys["remark"]])
    for col in range(1, 9):
        c = ws.cell(row=2, column=col)
        style_cell(c, SUBSYS_FONT, SUBSYS_FILL, LEFT_WRAP if col in (3, 4, 5, 7, 8) else CENTER_WRAP)
    # 模块与功能行
    for mod in subsys["modules"]:
        _level, m_code, m_name, m_req, m_resp, m_caps, m_src, m_remark, funcs = mod
        ws.append([LEVEL_MODULE, m_code, m_name, m_req, m_resp, m_caps, m_src, m_remark])
        r = ws.max_row
        for col in range(1, 9):
            c = ws.cell(row=r, column=col)
            style_cell(c, MODULE_FONT, MODULE_FILL, LEFT_WRAP if col in (3, 4, 5, 6, 7, 8) else CENTER_WRAP)
        for f in funcs:
            ws.append(list(f))
            r = ws.max_row
            for col in range(1, 9):
                c = ws.cell(row=r, column=col)
                style_cell(c, FUNC_FONT, None, LEFT_WRAP if col in (3, 4, 5, 6, 7, 8) else CENTER_WRAP)
    ws.freeze_panes = "A2"
    return ws


def build_overview_sheet(wb):
    ws = wb.create_sheet(title="模块清单总览")
    for i, w in enumerate(OVERVIEW_WIDTHS, start=1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    ws.append(OVERVIEW_HEADERS)
    for col in range(1, 8):
        c = ws.cell(row=1, column=col)
        style_cell(c, HEADER_FONT, HEADER_FILL, CENTER_WRAP)
    ws.row_dimensions[1].height = 26
    # 每个子系统一块：子系统行(A,B,C,F,G 填) + 模块行(D,E,F,G 填)
    for sub in SUBSYSTEMS:
        modules = sub["modules"]
        mod_count = len(modules)
        # 子系统行
        ws.append([sub["m_id"], sub["code"], f"{mod_count}个", None, None,
                   sub["req"], sub["resp"]])
        # 模块行
        for mod in modules:
            _lvl, m_code, m_name, m_req, m_resp, _caps, _src, _rem, _funcs = mod
            ws.append([None, None, None, m_code, m_name, m_req, m_resp])
    ws.freeze_panes = "A2"
    return ws


